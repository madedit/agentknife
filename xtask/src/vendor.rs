//! Vendored JS (AGENTS.md §2 "CodeMirror without Node").
//!
//! `cargo xtask vendor-codemirror` fetches one esm.sh bundle per module. Every other
//! vendored package is marked `external`, so shared packages such as `@codemirror/state`
//! exist exactly once and are resolved through the generated `importmap.json`.
//! `cargo xtask ci` verifies hashes and that the vendored versions match `versions.toml`.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;
use std::sync::LazyLock;

use regex::Regex;
use sha2::{Digest, Sha256};

use crate::Result;
use crate::versions::Versions;

const CODEMIRROR_DIR: &str = "crates/ak-shell/vendor/codemirror";
const SUMS_FILE: &str = "SHA256SUMS";
const MANIFEST_FILE: &str = "manifest.toml";
const IMPORTMAP_FILE: &str = "importmap.json";
const ESM_HOST: &str = "https://esm.sh";
/// The shell's page: browsers have no external import maps, so the map is inline.
const SHELL_INDEX: &str = "crates/ak-shell/index.html";
const MAP_BEGIN: &str = "<!-- codemirror importmap: written by `cargo xtask vendor-codemirror` -->";
const MAP_END: &str = "<!-- /codemirror importmap -->";
/// Where Trunk serves the vendored folder (`copy-dir` keeps its name).
const SERVED_DIR: &str = "./codemirror/";
const ESM_TARGET: &str = "es2022";

/// Module specifiers to vendor. A specifier's package is listed in versions.toml.
const CODEMIRROR_MODULES: &[&str] = &[
    "codemirror",
    "@codemirror/state",
    "@codemirror/view",
    "@codemirror/language",
    "@codemirror/commands",
    "@codemirror/autocomplete",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/lang-rust",
    "@codemirror/lang-css",
    "@codemirror/lang-html",
    "@codemirror/lang-markdown",
    "@codemirror/legacy-modes/mode/toml",
    "@codemirror/theme-one-dark",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
];

// INVARIANT: the pattern is a constant and covered by tests.
#[allow(clippy::expect_used)]
static IMPORT_RE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r#"(?:\bfrom|\bimport)\s*\(?\s*"((?:@|\.{1,2}/|/)?[A-Za-z0-9_][A-Za-z0-9_./@-]*)""#)
        .expect("valid regex")
});

/// `@scope/pkg/sub/path` -> `@scope/pkg`; `pkg/sub` -> `pkg`.
fn package_of(specifier: &str) -> &str {
    let n = if specifier.starts_with('@') { 2 } else { 1 };
    match specifier.match_indices('/').nth(n - 1) {
        Some((i, _)) => &specifier[..i],
        None => specifier,
    }
}

/// Vendored file path for a module, relative to the vendor dir.
fn file_of(specifier: &str) -> String {
    format!("{specifier}.mjs")
}

fn check_module_list(pinned: &BTreeMap<String, String>) -> Result<()> {
    let used: BTreeSet<&str> = CODEMIRROR_MODULES.iter().map(|m| package_of(m)).collect();
    let listed: BTreeSet<&str> = pinned.keys().map(String::as_str).collect();
    if used == listed {
        Ok(())
    } else {
        Err(format!(
            "versions.toml [vendor.codemirror] packages {listed:?} do not match \
             the modules xtask vendors {used:?}"
        )
        .into())
    }
}

pub fn vendor_codemirror(root: &Path) -> Result<()> {
    let pinned = Versions::load(root)?.vendor.codemirror;
    check_module_list(&pinned)?;
    let dir = root.join(CODEMIRROR_DIR);
    if dir.exists() {
        std::fs::remove_dir_all(&dir)?;
    }
    std::fs::create_dir_all(&dir)?;

    let mut sums = String::new();
    let mut pending = Vec::new();
    for module in CODEMIRROR_MODULES {
        let package = package_of(module);
        let version = &pinned[package];
        let subpath = &module[package.len()..];
        let external: Vec<&str> = CODEMIRROR_MODULES
            .iter()
            .copied()
            .filter(|m| m != module)
            .collect();
        let url = format!(
            "{ESM_HOST}/{package}@{version}{subpath}?bundle&target={ESM_TARGET}&external={}",
            external.join(",")
        );
        let code = fetch_module(&url)?;
        pending.extend(helper_imports(module, &code)?);
        write_file(&dir.join(file_of(module)), &code)?;
        println!("vendored {module}@{version} ({} bytes)", code.len());
    }

    // esm.sh helper modules (e.g. `/node/process.mjs`) are vendored byte-for-byte
    // under `_esm/` and resolved through the import map.
    let mut helpers = BTreeSet::new();
    while let Some(path) = pending.pop() {
        if !helpers.insert(path.clone()) {
            continue;
        }
        let code = ureq::get(&format!("{ESM_HOST}{path}"))
            .call()?
            .body_mut()
            .read_to_string()?;
        pending.extend(helper_imports(&path, &code)?);
        write_file(&dir.join(helper_file(&path)), &code)?;
        println!("vendored esm.sh helper {path} ({} bytes)", code.len());
    }

    let mut manifest =
        String::from("# Generated by `cargo xtask vendor-codemirror`. Do not edit.\n[packages]\n");
    for (package, version) in &pinned {
        manifest.push_str(&format!("\"{package}\" = \"{version}\"\n"));
    }
    std::fs::write(dir.join(MANIFEST_FILE), manifest)?;

    let mut imports = serde_json::Map::new();
    for module in CODEMIRROR_MODULES {
        imports.insert(
            (*module).to_owned(),
            format!("./{}", file_of(module)).into(),
        );
    }
    for path in &helpers {
        imports.insert(path.clone(), format!("./{}", helper_file(path)).into());
    }
    let map = serde_json::json!({ "imports": imports });
    std::fs::write(
        dir.join(IMPORTMAP_FILE),
        serde_json::to_string_pretty(&map)? + "\n",
    )?;

    for rel in list_files(&dir, &dir)? {
        let hash = sha256_hex(&std::fs::read(dir.join(&rel))?);
        sums.push_str(&format!("{hash}  {rel}\n"));
    }
    std::fs::write(dir.join(SUMS_FILE), sums)?;
    println!("wrote {CODEMIRROR_DIR}/{{{SUMS_FILE},{MANIFEST_FILE},{IMPORTMAP_FILE}}}");
    write_index(root)
}

/// `cargo xtask vendor-codemirror index`: only rewrites the shell page's map.
pub fn write_index(root: &Path) -> Result<()> {
    let map = std::fs::read_to_string(root.join(CODEMIRROR_DIR).join(IMPORTMAP_FILE))?;
    let index_path = root.join(SHELL_INDEX);
    let index = std::fs::read_to_string(&index_path)?;
    std::fs::write(&index_path, with_inline_map(&index, &map)?)?;
    println!("wrote the import map into {SHELL_INDEX}");
    Ok(())
}

/// The `<script type="importmap">` for the page: importmap.json with every file
/// under [`SERVED_DIR`].
fn inline_map(importmap_json: &str) -> Result<String> {
    let map: serde_json::Value = serde_json::from_str(importmap_json)?;
    let mut imports = serde_json::Map::new();
    for (k, v) in map["imports"].as_object().into_iter().flatten() {
        let file = v.as_str().unwrap_or_default().trim_start_matches("./");
        imports.insert(k.clone(), format!("{SERVED_DIR}{file}").into());
    }
    let json = serde_json::to_string_pretty(&serde_json::json!({ "imports": imports }))?;
    let body = json.replace('\n', "\n      ");
    Ok(format!(
        "{MAP_BEGIN}\n    <script type=\"importmap\">\n      {body}\n    </script>\n    {MAP_END}"
    ))
}

/// `index` with its marked block replaced by the current map.
fn with_inline_map(index: &str, importmap_json: &str) -> Result<String> {
    let (Some(start), Some(end)) = (index.find(MAP_BEGIN), index.find(MAP_END)) else {
        return Err(format!("{SHELL_INDEX}: missing the import map markers").into());
    };
    Ok(format!(
        "{}{}{}",
        &index[..start],
        inline_map(importmap_json)?,
        &index[end + MAP_END.len()..]
    ))
}

fn helper_file(path: &str) -> String {
    format!("_esm{path}")
}

fn write_file(path: &Path, contents: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    Ok(std::fs::write(path, contents)?)
}

/// Returns the esm.sh helper paths a module imports; fails on any other
/// specifier that is not a vendored module.
fn helper_imports(module: &str, code: &str) -> Result<Vec<String>> {
    let (helpers, stray): (Vec<String>, Vec<String>) = imports(code)
        .into_iter()
        .filter(|s| !CODEMIRROR_MODULES.contains(&s.as_str()))
        .partition(|s| s.starts_with('/') && !s.starts_with("//"));
    if stray.is_empty() {
        Ok(helpers)
    } else {
        Err(format!("{module}: imports non-vendored modules {stray:?}").into())
    }
}

/// esm.sh answers with a stub that re-exports the real module named in `X-Esm-Path`.
fn fetch_module(url: &str) -> Result<String> {
    let stub = ureq::get(url).call()?;
    let path = stub
        .headers()
        .get("x-esm-path")
        .and_then(|v| v.to_str().ok())
        .ok_or_else(|| format!("{url}: no X-Esm-Path header"))?
        .to_owned();
    Ok(ureq::get(&format!("{ESM_HOST}{path}"))
        .call()?
        .body_mut()
        .read_to_string()?)
}

/// Static and dynamic import specifiers in an ES module.
fn imports(code: &str) -> BTreeSet<String> {
    IMPORT_RE
        .captures_iter(code)
        .map(|c| c[1].to_owned())
        .collect()
}

pub fn check(root: &Path) -> Result<()> {
    let dir = root.join(CODEMIRROR_DIR);
    // Absent until CodeMirror is vendored.
    if !dir.is_dir() {
        return Ok(());
    }
    let mut errors = verify_dir(&dir)?;
    let pinned = Versions::load(root)?.vendor.codemirror;
    match std::fs::read_to_string(dir.join(MANIFEST_FILE)) {
        Ok(text) => {
            let t: toml::Table = toml::from_str(&text)?;
            let vendored: BTreeMap<String, String> = t
                .get("packages")
                .and_then(|p| p.as_table())
                .map(|p| {
                    p.iter()
                        .filter_map(|(k, v)| Some((k.clone(), v.as_str()?.to_owned())))
                        .collect()
                })
                .unwrap_or_default();
            if vendored != pinned {
                errors.push(format!(
                    "{CODEMIRROR_DIR}: vendored versions differ from versions.toml; \
                     run `cargo xtask vendor-codemirror`"
                ));
            }
        }
        Err(_) => errors.push(format!("{CODEMIRROR_DIR}: missing {MANIFEST_FILE}")),
    }
    errors.extend(unresolved_imports(&dir)?);
    let map = std::fs::read_to_string(dir.join(IMPORTMAP_FILE)).unwrap_or_default();
    match std::fs::read_to_string(root.join(SHELL_INDEX)) {
        Ok(index) => match with_inline_map(&index, &map) {
            Ok(expected) if expected == index => {}
            Ok(_) => errors.push(format!(
                "{SHELL_INDEX}: the import map is stale; run `cargo xtask vendor-codemirror index`"
            )),
            Err(e) => errors.push(e.to_string()),
        },
        Err(_) => errors.push(format!("{SHELL_INDEX}: missing")),
    }
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors.join("\n").into())
    }
}

/// Every import in every vendored module must be a key of `importmap.json`
/// that points at an existing file.
fn unresolved_imports(dir: &Path) -> Result<Vec<String>> {
    let Ok(text) = std::fs::read_to_string(dir.join(IMPORTMAP_FILE)) else {
        return Ok(vec![format!("{}: missing {IMPORTMAP_FILE}", dir.display())]);
    };
    let map: serde_json::Value = serde_json::from_str(&text)?;
    let empty = serde_json::Map::new();
    let entries = map
        .get("imports")
        .and_then(|i| i.as_object())
        .unwrap_or(&empty);
    let mut errors = Vec::new();
    for (key, target) in entries {
        let rel = target.as_str().unwrap_or_default().trim_start_matches("./");
        if !dir.join(rel).is_file() {
            errors.push(format!("{IMPORTMAP_FILE}: {key} -> missing file {rel}"));
        }
    }
    for rel in list_files(dir, dir)? {
        if !rel.ends_with(".mjs") {
            continue;
        }
        for spec in imports(&std::fs::read_to_string(dir.join(&rel))?) {
            if !entries.contains_key(&spec) {
                errors.push(format!("{rel}: import {spec:?} not in {IMPORTMAP_FILE}"));
            }
        }
    }
    Ok(errors)
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// Parses `<hex>  <relative/path>` lines.
fn parse_sums(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .filter_map(|l| l.split_once("  "))
        .map(|(hash, path)| (path.trim().to_owned(), hash.trim().to_owned()))
        .collect()
}

fn verify_dir(dir: &Path) -> Result<Vec<String>> {
    let label = dir.display();
    let Ok(text) = std::fs::read_to_string(dir.join(SUMS_FILE)) else {
        return Ok(vec![format!("{label}: missing {SUMS_FILE}")]);
    };
    let mut expected = parse_sums(&text);
    let mut errors = Vec::new();
    for rel in list_files(dir, dir)? {
        if rel == SUMS_FILE {
            continue;
        }
        let actual = sha256_hex(&std::fs::read(dir.join(&rel))?);
        match expected.remove(&rel) {
            Some(hash) if hash == actual => {}
            Some(_) => errors.push(format!("{label}/{rel}: hash mismatch")),
            None => errors.push(format!("{label}/{rel}: not listed in {SUMS_FILE}")),
        }
    }
    for rel in expected.keys() {
        errors.push(format!("{label}/{rel}: listed in {SUMS_FILE} but missing"));
    }
    Ok(errors)
}

/// Lists files under `dir` as sorted `/`-separated paths relative to `base`.
fn list_files(base: &Path, dir: &Path) -> Result<Vec<String>> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            out.extend(list_files(base, &path)?);
        } else if let Ok(rel) = path.strip_prefix(base) {
            let parts: Vec<_> = rel.iter().map(|p| p.to_string_lossy()).collect();
            out.push(parts.join("/"));
        }
    }
    out.sort();
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vendor_dir(files: &[(&str, &str)], sums: &str) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        for (name, content) in files {
            let path = dir.path().join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, content).unwrap();
        }
        std::fs::write(dir.path().join(SUMS_FILE), sums).unwrap();
        dir
    }

    #[test]
    fn matching_hashes_pass() {
        let sums = format!(
            "{}  a.js\n{}  sub/b.js\n",
            sha256_hex(b"aaa"),
            sha256_hex(b"bbb")
        );
        let dir = vendor_dir(&[("a.js", "aaa"), ("sub/b.js", "bbb")], &sums);
        assert!(verify_dir(dir.path()).unwrap().is_empty());
    }

    #[test]
    fn changed_byte_fails() {
        let sums = format!("{}  a.js\n", sha256_hex(b"aaa"));
        let dir = vendor_dir(&[("a.js", "aab")], &sums);
        assert_eq!(verify_dir(dir.path()).unwrap().len(), 1);
    }

    #[test]
    fn unlisted_and_missing_files_fail() {
        let sums = format!("{}  gone.js\n", sha256_hex(b"x"));
        let dir = vendor_dir(&[("extra.js", "y")], &sums);
        assert_eq!(verify_dir(dir.path()).unwrap().len(), 2);
    }

    #[test]
    fn unresolved_import_fails() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("a.mjs"), r#"import{x}from"b";"#).unwrap();
        std::fs::write(dir.path().join("b.mjs"), "export const x=1;").unwrap();
        let map = r#"{"imports":{"b":"./b.mjs"}}"#;
        std::fs::write(dir.path().join(IMPORTMAP_FILE), map).unwrap();
        assert!(unresolved_imports(dir.path()).unwrap().is_empty());
        std::fs::write(dir.path().join("a.mjs"), r#"import{x}from"c";"#).unwrap();
        assert_eq!(unresolved_imports(dir.path()).unwrap().len(), 1);
    }

    #[test]
    fn package_of_strips_subpaths() {
        assert_eq!(package_of("codemirror"), "codemirror");
        assert_eq!(package_of("@codemirror/state"), "@codemirror/state");
        assert_eq!(
            package_of("@codemirror/legacy-modes/mode/toml"),
            "@codemirror/legacy-modes"
        );
    }

    #[test]
    fn imports_finds_static_and_dynamic() {
        let code =
            r#"import{a as b}from"@lezer/lr";import "x";export*from "y";const m=import("z");"#;
        let found: Vec<String> = imports(code).into_iter().collect();
        assert_eq!(found, ["@lezer/lr", "x", "y", "z"]);
    }

    #[test]
    fn imports_ignores_keyword_data_strings() {
        // lang-css ships keyword tables like this.
        let code = r#"const k="import,from",":204,";x=["from",":204,"];"#;
        assert!(imports(code).is_empty());
    }

    #[test]
    fn module_list_must_match_versions() {
        let mut pinned: BTreeMap<String, String> = CODEMIRROR_MODULES
            .iter()
            .map(|m| (package_of(m).to_owned(), "1.0.0".to_owned()))
            .collect();
        assert!(check_module_list(&pinned).is_ok());
        pinned.insert("@codemirror/extra".to_owned(), "1.0.0".to_owned());
        assert!(check_module_list(&pinned).is_err());
    }
}
