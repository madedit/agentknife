//! `versions.toml` is the single source of pinned versions (AGENTS.md §2).

use std::collections::BTreeMap;
use std::path::Path;

use serde::Deserialize;

use crate::Result;

#[derive(Deserialize)]
pub struct Versions {
    pub rust: RustVersions,
    /// Crates pinned with `=` in the workspace and in templates.
    pub crates: BTreeMap<String, String>,
    pub knowledge: KnowledgeVersions,
}

#[derive(Deserialize)]
pub struct RustVersions {
    pub toolchain: String,
}

#[derive(Deserialize)]
pub struct KnowledgeVersions {
    pub pack: String,
}

/// Crates in `versions.toml` that are CLI tools, not library dependencies.
const CLI_ONLY: &[&str] = &["tauri-cli"];

impl Versions {
    pub fn load(root: &Path) -> Result<Self> {
        Ok(toml::from_str(&std::fs::read_to_string(
            root.join("versions.toml"),
        )?)?)
    }
}

/// Renders `rust-toolchain.toml` from `versions.toml`.
pub fn render_toolchain(versions: &Versions) -> String {
    format!(
        "# Generated by `cargo xtask gen-toolchain` from versions.toml. Do not edit.\n\
         [toolchain]\n\
         channel = \"{}\"\n\
         components = [\"rustfmt\", \"clippy\"]\n\
         targets = [\"wasm32-unknown-unknown\"]\n",
        versions.rust.toolchain
    )
}

pub fn check(root: &Path) -> Result<()> {
    let versions = Versions::load(root)?;
    let mut errors = Vec::new();

    let toolchain = std::fs::read_to_string(root.join("rust-toolchain.toml")).unwrap_or_default();
    if toolchain.replace("\r\n", "\n") != render_toolchain(&versions) {
        errors
            .push("rust-toolchain.toml is out of date; run `cargo xtask gen-toolchain`".to_owned());
    }

    let manifest: toml::Table = toml::from_str(&std::fs::read_to_string(root.join("Cargo.toml"))?)?;
    errors.extend(manifest_drift(
        "Cargo.toml [workspace.dependencies]",
        manifest
            .get("workspace")
            .and_then(|w| w.get("dependencies")),
        &versions,
        true,
    ));

    // Stack-profile templates: any pinned crate they use must match.
    let templates = root.join("templates");
    if templates.is_dir() {
        for entry in std::fs::read_dir(&templates)? {
            let path = entry?.path().join("Cargo.toml");
            if !path.is_file() {
                continue;
            }
            let t: toml::Table = toml::from_str(&std::fs::read_to_string(&path)?)?;
            errors.extend(manifest_drift(
                &path.display().to_string(),
                t.get("dependencies"),
                &versions,
                false,
            ));
        }
    }

    // Knowledge pack metadata: knowledge/pack.toml [pack] version.
    let pack = root.join("knowledge").join("pack.toml");
    if pack.is_file() {
        let t: toml::Table = toml::from_str(&std::fs::read_to_string(&pack)?)?;
        let v = t
            .get("pack")
            .and_then(|p| p.get("version"))
            .and_then(|v| v.as_str());
        if v != Some(versions.knowledge.pack.as_str()) {
            errors.push(format!(
                "knowledge/pack.toml version {v:?} != versions.toml {}",
                versions.knowledge.pack
            ));
        }
    }

    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors.join("\n").into())
    }
}

/// Compares a `[dependencies]`-style table against the pinned crates.
/// With `require_all`, every pinned library crate must be present.
fn manifest_drift(
    label: &str,
    deps: Option<&toml::Value>,
    versions: &Versions,
    require_all: bool,
) -> Vec<String> {
    let mut errors = Vec::new();
    for (name, pinned) in &versions.crates {
        if CLI_ONLY.contains(&name.as_str()) {
            continue;
        }
        let dep = deps.and_then(|d| d.get(name));
        let found = dep.and_then(|d| {
            d.as_str()
                .or_else(|| d.get("version").and_then(|v| v.as_str()))
        });
        let expected = format!("={pinned}");
        match (dep, found) {
            (None, _) if !require_all => {}
            // `{ workspace = true }` inherits the checked workspace pin.
            (Some(d), None) if d.get("workspace").and_then(|w| w.as_bool()) == Some(true) => {}
            (_, Some(v)) if v == expected => {}
            (_, v) => errors.push(format!("{label}: {name} is {v:?}, expected \"{expected}\"")),
        }
    }
    errors
}

#[cfg(test)]
mod tests {
    use super::*;

    fn versions() -> Versions {
        toml::from_str(
            "[rust]\ntoolchain = \"1.2.3\"\n\
             [crates]\ntauri = \"2.0.0\"\ntauri-cli = \"2.0.1\"\n\
             [knowledge]\npack = \"0.1.0\"\n",
        )
        .unwrap()
    }

    fn deps(src: &str) -> toml::Value {
        toml::Value::Table(toml::from_str(src).unwrap())
    }

    #[test]
    fn toolchain_uses_pinned_channel() {
        let out = render_toolchain(&versions());
        assert!(out.contains("channel = \"1.2.3\""));
        assert!(out.contains("wasm32-unknown-unknown"));
    }

    #[test]
    fn matching_pin_passes() {
        let d = deps("tauri = \"=2.0.0\"");
        assert!(manifest_drift("x", Some(&d), &versions(), true).is_empty());
        let d = deps("tauri = { version = \"=2.0.0\", features = [] }");
        assert!(manifest_drift("x", Some(&d), &versions(), true).is_empty());
        let d = deps("tauri = { workspace = true }");
        assert!(manifest_drift("x", Some(&d), &versions(), false).is_empty());
    }

    #[test]
    fn drifted_or_unpinned_fails() {
        let d = deps("tauri = \"=2.0.9\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
        let d = deps("tauri = \"2.0.0\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
    }

    #[test]
    fn missing_pin_fails_only_when_required() {
        let d = deps("serde = \"1\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
        assert!(manifest_drift("x", Some(&d), &versions(), false).is_empty());
    }
}
