//! `versions.toml` is the single source of pinned versions (AGENTS.md §2).

use std::collections::BTreeMap;
use std::path::Path;

use serde::Deserialize;

use crate::Result;

#[derive(Deserialize)]
pub struct Versions {
    pub rust: RustVersions,
    /// Crates pinned with `=` in the workspace and in templates.
    pub crates: BTreeMap<String, String>,
    pub knowledge: KnowledgeVersions,
    #[serde(default)]
    pub vendor: VendorVersions,
    /// Standalone tools (`trunk`, `tailwind-cli`, `rustup`).
    #[serde(default)]
    pub tools: BTreeMap<String, String>,
}

#[derive(Deserialize, Default)]
pub struct VendorVersions {
    /// npm package -> exact version, vendored by `cargo xtask vendor-codemirror`.
    #[serde(default)]
    pub codemirror: BTreeMap<String, String>,
    /// npm package -> exact version, vendored by `cargo xtask vendor-libs` for
    /// generated apps (`add_library`).
    #[serde(default)]
    pub libraries: BTreeMap<String, String>,
}

#[derive(Deserialize)]
pub struct RustVersions {
    pub toolchain: String,
}

#[derive(Deserialize)]
pub struct KnowledgeVersions {
    pub pack: String,
}

/// Crates in `versions.toml` that are CLI tools, not library dependencies.
const CLI_ONLY: &[&str] = &["tauri-cli"];

impl Versions {
    pub fn load(root: &Path) -> Result<Self> {
        Ok(toml::from_str(&std::fs::read_to_string(
            root.join("versions.toml"),
        )?)?)
    }
}

/// Renders `rust-toolchain.toml` from `versions.toml`.
pub fn render_toolchain(versions: &Versions) -> String {
    format!(
        "# Generated by `cargo xtask gen-toolchain` from versions.toml. Do not edit.\n\
         [toolchain]\n\
         channel = \"{}\"\n\
         components = [\"rustfmt\", \"clippy\"]\n\
         targets = [\"wasm32-unknown-unknown\"]\n",
        versions.rust.toolchain
    )
}

pub fn check(root: &Path) -> Result<()> {
    let versions = Versions::load(root)?;
    let mut errors = Vec::new();

    let toolchain = std::fs::read_to_string(root.join("rust-toolchain.toml")).unwrap_or_default();
    if toolchain.replace("\r\n", "\n") != render_toolchain(&versions) {
        errors
            .push("rust-toolchain.toml is out of date; run `cargo xtask gen-toolchain`".to_owned());
    }

    let manifest: toml::Table = toml::from_str(&std::fs::read_to_string(root.join("Cargo.toml"))?)?;
    errors.extend(manifest_drift(
        "Cargo.toml [workspace.dependencies]",
        manifest
            .get("workspace")
            .and_then(|w| w.get("dependencies")),
        &versions,
        true,
    ));

    // Stack-profile templates: pinned crates in every manifest, the tool versions
    // trunk is told to use, and what the template's lockfile resolved.
    let templates = root.join("templates");
    if templates.is_dir() {
        for entry in std::fs::read_dir(&templates)? {
            let dir = entry?.path();
            errors.extend(template_drift(&dir, &versions)?);
        }
    }

    // Knowledge packs: knowledge/<stack>/pack.toml.
    let knowledge = root.join("knowledge");
    if knowledge.is_dir() {
        for entry in std::fs::read_dir(&knowledge)? {
            let dir = entry?.path();
            if dir.join("pack.toml").is_file() {
                errors.extend(knowledge_drift(&dir, &versions)?);
            }
        }
    }

    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors.join("\n").into())
    }
}

/// Compares a `[dependencies]`-style table against the pinned crates.
/// With `require_all`, every pinned library crate must be present.
/// Version drift in one template folder (nothing to check if it has no Cargo.toml).
fn template_drift(dir: &Path, versions: &Versions) -> Result<Vec<String>> {
    let mut errors = Vec::new();
    if !dir.join("Cargo.toml").is_file() {
        return Ok(errors);
    }
    for manifest in [
        dir.join("Cargo.toml"),
        dir.join("src-tauri").join("Cargo.toml"),
    ] {
        if !manifest.is_file() {
            continue;
        }
        let t: toml::Table = toml::from_str(&std::fs::read_to_string(&manifest)?)?;
        for section in ["dependencies", "build-dependencies"] {
            errors.extend(manifest_drift(
                &format!("{} [{section}]", manifest.display()),
                t.get(section),
                versions,
                false,
            ));
        }
    }
    let trunk = dir.join("Trunk.toml");
    if trunk.is_file() {
        let t: toml::Table = toml::from_str(&std::fs::read_to_string(&trunk)?)?;
        let tools = t.get("tools");
        let want = [
            ("wasm_bindgen", versions.crates.get("wasm-bindgen")),
            ("tailwindcss", versions.tools.get("tailwind-cli")),
        ];
        for (key, pinned) in want {
            let found = tools.and_then(|t| t.get(key)).and_then(|v| v.as_str());
            if found != pinned.map(String::as_str) {
                errors.push(format!(
                    "{}: [tools] {key} is {found:?}, expected {pinned:?}",
                    trunk.display()
                ));
            }
        }
    }
    let lock = dir.join("Cargo.lock");
    if lock.is_file() {
        let t: toml::Table = toml::from_str(&std::fs::read_to_string(&lock)?)?;
        let packages = t.get("package").and_then(|p| p.as_array());
        for (name, pinned) in &versions.crates {
            if CLI_ONLY.contains(&name.as_str()) {
                continue;
            }
            let locked: Vec<&str> = packages
                .into_iter()
                .flatten()
                .filter(|p| p.get("name").and_then(|n| n.as_str()) == Some(name.as_str()))
                .filter_map(|p| p.get("version").and_then(|v| v.as_str()))
                .collect();
            if locked.iter().any(|v| v != pinned) {
                errors.push(format!(
                    "{}: {name} locked at {locked:?}, expected {pinned}",
                    lock.display()
                ));
            }
        }
    }
    Ok(errors)
}

/// One knowledge pack: its version, the versions its docs describe, and that
/// every topic file exists, is listed, and every ``topic `id` `` mention resolves.
fn knowledge_drift(dir: &Path, versions: &Versions) -> Result<Vec<String>> {
    let mut errors = Vec::new();
    let label = dir.join("pack.toml").display().to_string();
    let t: toml::Table = toml::from_str(&std::fs::read_to_string(dir.join("pack.toml"))?)?;
    let v = t
        .get("pack")
        .and_then(|p| p.get("version"))
        .and_then(|v| v.as_str());
    if v != Some(versions.knowledge.pack.as_str()) {
        errors.push(format!(
            "{label}: version {v:?} != versions.toml [knowledge] pack {}",
            versions.knowledge.pack
        ));
    }
    if let Some(described) = t.get("versions").and_then(|v| v.as_table()) {
        for (name, value) in described {
            let pinned = versions
                .crates
                .get(name)
                .or_else(|| versions.tools.get(name));
            if pinned.map(String::as_str) != value.as_str() {
                errors.push(format!(
                    "{label}: describes {name} {value}, but versions.toml pins {pinned:?}"
                ));
            }
        }
    }
    let topics = t
        .get("topic")
        .and_then(|v| v.as_array())
        .cloned()
        .unwrap_or_default();
    let ids: Vec<&str> = topics
        .iter()
        .filter_map(|t| t.get("id").and_then(|v| v.as_str()))
        .collect();
    let mut files = Vec::new();
    for topic in &topics {
        let id = topic.get("id").and_then(|v| v.as_str()).unwrap_or("?");
        for key in ["title", "summary", "file"] {
            if topic
                .get(key)
                .and_then(|v| v.as_str())
                .is_none_or(str::is_empty)
            {
                errors.push(format!("{label}: topic {id} has no {key}"));
            }
        }
        let Some(file) = topic.get("file").and_then(|v| v.as_str()) else {
            continue;
        };
        files.push(file.to_owned());
        let Ok(text) = std::fs::read_to_string(dir.join(file)) else {
            errors.push(format!("{label}: topic {id}: {file} does not exist"));
            continue;
        };
        // "topic `x`" in the text must name a real topic.
        for part in text.split("topic `").skip(1) {
            let mentioned = part.split('`').next().unwrap_or_default();
            if !ids.contains(&mentioned) {
                errors.push(format!("{file}: mentions unknown topic `{mentioned}`"));
            }
        }
    }
    let mut seen = std::collections::BTreeSet::new();
    for id in &ids {
        if !seen.insert(*id) {
            errors.push(format!("{label}: topic {id} is listed twice"));
        }
    }
    for entry in std::fs::read_dir(dir)? {
        let name = entry?.file_name().to_string_lossy().into_owned();
        if name.ends_with(".md") && !files.contains(&name) {
            errors.push(format!("{label}: {name} is not listed as a topic"));
        }
    }
    Ok(errors)
}

fn manifest_drift(
    label: &str,
    deps: Option<&toml::Value>,
    versions: &Versions,
    require_all: bool,
) -> Vec<String> {
    let mut errors = Vec::new();
    for (name, pinned) in &versions.crates {
        if CLI_ONLY.contains(&name.as_str()) {
            continue;
        }
        let dep = deps.and_then(|d| d.get(name));
        let found = dep.and_then(|d| {
            d.as_str()
                .or_else(|| d.get("version").and_then(|v| v.as_str()))
        });
        let expected = format!("={pinned}");
        match (dep, found) {
            (None, _) if !require_all => {}
            // `{ workspace = true }` inherits the checked workspace pin.
            (Some(d), None) if d.get("workspace").and_then(|w| w.as_bool()) == Some(true) => {}
            (_, Some(v)) if v == expected => {}
            (_, v) => errors.push(format!("{label}: {name} is {v:?}, expected \"{expected}\"")),
        }
    }
    errors
}

#[cfg(test)]
mod tests {
    use super::*;

    fn versions() -> Versions {
        toml::from_str(
            "[rust]\ntoolchain = \"1.2.3\"\n\
             [crates]\ntauri = \"2.0.0\"\ntauri-cli = \"2.0.1\"\n\
             [knowledge]\npack = \"0.1.0\"\n",
        )
        .unwrap()
    }

    #[test]
    fn knowledge_pack_drift_is_caught() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(
            dir.path().join("pack.toml"),
            "[pack]\nid = \"s\"\nversion = \"0.2.0\"\n\
             [versions]\ntauri = \"1.9.9\"\n\
             [[topic]]\nid = \"a\"\ntitle = \"A\"\nsummary = \"s\"\nfile = \"a.md\"\n\
             [[topic]]\nid = \"b\"\ntitle = \"B\"\nsummary = \"s\"\nfile = \"missing.md\"\n",
        )
        .unwrap();
        std::fs::write(
            dir.path().join("a.md"),
            "# A\nSee topic `b` and topic `nope`.",
        )
        .unwrap();
        std::fs::write(dir.path().join("stray.md"), "# not listed").unwrap();
        let errors = knowledge_drift(dir.path(), &versions()).unwrap().join("\n");
        assert!(errors.contains("version Some(\"0.2.0\")"), "{errors}");
        assert!(errors.contains("describes tauri \"1.9.9\""), "{errors}");
        assert!(errors.contains("missing.md does not exist"), "{errors}");
        assert!(errors.contains("unknown topic `nope`"), "{errors}");
        assert!(!errors.contains("unknown topic `b`"), "{errors}");
        assert!(errors.contains("stray.md is not listed"), "{errors}");
    }

    fn deps(src: &str) -> toml::Value {
        toml::Value::Table(toml::from_str(src).unwrap())
    }

    #[test]
    fn toolchain_uses_pinned_channel() {
        let out = render_toolchain(&versions());
        assert!(out.contains("channel = \"1.2.3\""));
        assert!(out.contains("wasm32-unknown-unknown"));
    }

    #[test]
    fn matching_pin_passes() {
        let d = deps("tauri = \"=2.0.0\"");
        assert!(manifest_drift("x", Some(&d), &versions(), true).is_empty());
        let d = deps("tauri = { version = \"=2.0.0\", features = [] }");
        assert!(manifest_drift("x", Some(&d), &versions(), true).is_empty());
        let d = deps("tauri = { workspace = true }");
        assert!(manifest_drift("x", Some(&d), &versions(), false).is_empty());
    }

    #[test]
    fn drifted_or_unpinned_fails() {
        let d = deps("tauri = \"=2.0.9\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
        let d = deps("tauri = \"2.0.0\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
    }

    #[test]
    fn missing_pin_fails_only_when_required() {
        let d = deps("serde = \"1\"");
        assert_eq!(manifest_drift("x", Some(&d), &versions(), true).len(), 1);
        assert!(manifest_drift("x", Some(&d), &versions(), false).is_empty());
    }
}
