//! `cargo xtask pin-downloads`: records the sha256 of every prebuilt download in
//! `versions.toml` `[downloads]`, and the CI check that they match the pins.

use std::collections::BTreeMap;
use std::path::Path;

use ak_doctor::Pinned;
use ak_doctor::assets::{all_assets, parse_checksum};

use crate::Result;
use crate::vendor::sha256_hex;

const SECTION: &str = "[downloads]";

fn read_pinned(root: &Path) -> Result<(String, Pinned)> {
    let text = std::fs::read_to_string(root.join("versions.toml"))?;
    let pinned = Pinned::parse(&text)?;
    Ok((text, pinned))
}

fn fetch(url: &str) -> Result<Vec<u8>> {
    Ok(ureq::get(url)
        .call()?
        .body_mut()
        .with_config()
        .limit(512 * 1024 * 1024)
        .read_to_vec()?)
}

pub fn pin(root: &Path) -> Result<()> {
    let (text, pinned) = read_pinned(root)?;
    let mut sums = BTreeMap::new();
    for asset in all_assets(&pinned) {
        let hash = match &asset.checksum_url {
            Some(url) => {
                let body = String::from_utf8(fetch(url)?)?;
                parse_checksum(&body, &asset.file_name)
                    .ok_or_else(|| format!("{url}: no checksum for {}", asset.file_name))?
            }
            // No published checksum (tauri-cli): hash the download itself.
            None => sha256_hex(&fetch(&asset.url)?),
        };
        println!("{}  {}", &hash[..12], asset.key);
        sums.insert(asset.key, hash);
    }
    let mut section = format!(
        "{SECTION}\n# sha256 of each prebuilt download. Generated by `cargo xtask pin-downloads`.\n"
    );
    for (k, v) in &sums {
        section.push_str(&format!("\"{k}\" = \"{v}\"\n"));
    }
    std::fs::write(root.join("versions.toml"), replace_section(&text, &section))?;
    println!("pinned {} downloads", sums.len());
    Ok(())
}

/// Replaces (or appends) the `[downloads]` section.
fn replace_section(text: &str, section: &str) -> String {
    let mut out = String::new();
    let mut skipping = false;
    for line in text.lines() {
        let header = line.trim_start().starts_with('[') && !line.trim_start().starts_with("[[");
        if header {
            skipping = line.trim() == SECTION;
        }
        if !skipping {
            out.push_str(line);
            out.push('\n');
        }
    }
    let trimmed = out.trim_end().to_owned();
    format!("{trimmed}\n\n{section}")
}

/// CI: every prebuilt download has a checksum for the pinned version, and no stale
/// entries remain.
pub fn check(root: &Path) -> Result<()> {
    let (_, pinned) = read_pinned(root)?;
    let wanted: Vec<String> = all_assets(&pinned).into_iter().map(|a| a.key).collect();
    let mut errors = Vec::new();
    for key in &wanted {
        if !pinned.downloads.contains_key(key) {
            errors.push(format!("[downloads] is missing {key}"));
        }
    }
    for key in pinned.downloads.keys() {
        if !wanted.contains(key) {
            errors.push(format!("[downloads] has a stale entry {key}"));
        }
    }
    if errors.is_empty() {
        Ok(())
    } else {
        errors.push("run `cargo xtask pin-downloads`".into());
        Err(errors.join("\n").into())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn section_is_replaced_not_duplicated() {
        let text =
            "[tools]\na = \"1\"\n\n[downloads]\n\"old\" = \"x\"\n\n[knowledge]\npack = \"0\"\n";
        let out = replace_section(text, "[downloads]\n\"new\" = \"y\"\n");
        assert_eq!(out.matches("[downloads]").count(), 1);
        assert!(out.contains("\"new\"") && !out.contains("\"old\""));
        assert!(out.contains("[knowledge]\npack = \"0\""));
        let appended = replace_section("[tools]\n", "[downloads]\n");
        assert!(appended.ends_with("[downloads]\n"));
    }
}
