//! Dev tasks for the AgentKnife workspace. Run with `cargo xtask <command>`.

#![forbid(unsafe_code)]

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde::Deserialize;

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

#[derive(Deserialize)]
struct Versions {
    rust: RustVersions,
}

#[derive(Deserialize)]
struct RustVersions {
    toolchain: String,
}

fn main() -> ExitCode {
    let cmd = std::env::args().nth(1);
    let result = match cmd.as_deref() {
        Some("gen-toolchain") => gen_toolchain(),
        Some("ci") => Err("`cargo xtask ci` is not implemented yet (task P1-CORE-002)".into()),
        _ => {
            eprintln!("usage: cargo xtask <gen-toolchain|ci>");
            return ExitCode::FAILURE;
        }
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("xtask: {e}");
            ExitCode::FAILURE
        }
    }
}

fn workspace_root() -> PathBuf {
    // xtask/ lives directly under the workspace root.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."))
}

fn read_versions(root: &Path) -> Result<Versions> {
    let text = std::fs::read_to_string(root.join("versions.toml"))?;
    Ok(toml::from_str(&text)?)
}

/// Renders `rust-toolchain.toml` from `versions.toml`.
fn render_toolchain(versions: &Versions) -> String {
    format!(
        "# Generated by `cargo xtask gen-toolchain` from versions.toml. Do not edit.\n\
         [toolchain]\n\
         channel = \"{}\"\n\
         components = [\"rustfmt\", \"clippy\"]\n\
         targets = [\"wasm32-unknown-unknown\"]\n",
        versions.rust.toolchain
    )
}

fn gen_toolchain() -> Result<()> {
    let root = workspace_root();
    let versions = read_versions(&root)?;
    std::fs::write(
        root.join("rust-toolchain.toml"),
        render_toolchain(&versions),
    )?;
    println!(
        "wrote rust-toolchain.toml (rust {})",
        versions.rust.toolchain
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn toolchain_uses_pinned_channel() {
        let versions: Versions = toml::from_str("[rust]\ntoolchain = \"1.2.3\"\n").unwrap();
        let out = render_toolchain(&versions);
        assert!(out.contains("channel = \"1.2.3\""));
        assert!(out.contains("wasm32-unknown-unknown"));
    }
}
